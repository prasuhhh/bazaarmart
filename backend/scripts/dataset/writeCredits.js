// Writes docs/IMAGE_CREDITS.md from the catalogue, so the credits can't drift from the data.
import { readFileSync, writeFileSync } from 'node:fs';

const PRODUCTS = new URL('../../data/products-300.verified.json', import.meta.url);
const OUTPUT = new URL('../../../docs/IMAGE_CREDITS.md', import.meta.url);

const cell = text => String(text ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ');
const credited = JSON.parse(readFileSync(PRODUCTS, 'utf8')).filter(({ image }) => image?.status === 'ok');
const rows = credited.map(({ productId, productName, image }) =>
  `| ${productId} | ${cell(productName)} | [${cell(image.attribution)}](${image.sourcePage}) | ${cell(image.licence)} |`);

writeFileSync(OUTPUT, `# Image credits

${credited.length} product photos. Brand and product names are trademarks of their owners. Openly licensed
photos are credited below. Brand images are used only for a non-commercial student lab demo.

Generated by \`npm run catalogue:credits\`. Do not edit by hand.

| SKU | Product | Credit | Licence |
| --- | --- | --- | --- |
${rows.join('\n')}
`);
console.log(`Credited ${credited.length} photos.`);
